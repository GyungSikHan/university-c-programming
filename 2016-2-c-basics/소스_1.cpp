/*[포인터]
-포인터는 주기억 장치의 의치 주소를 받는 변수를 의미한다.
-32bit 컴퓨터서 메모리의 주소는 4Byte를 갖게 되며 포인터는 이에 대한 정보를 
저장하기때문에 자료형에 관계없이 4Byte의 크기를 갖는다.
(64Bit 컴퓨터에서 메모리의 주소는 8Bytr를 갖는다.)

[32Bit 운영체제와 64Bit 운영체제의 차이점]
-CPU가 한번에 처리할 수 있는 데이터의 크기를 나타낸다.
-32Bit 운영체제의 경우 한번에 32Bit 만큼의 데이터 처리를 하고,
64Bit 운영체제의 경우 한번에 64Bit 만큼의 데이터를 처리한다.
-32Bit 운영체제의 경우 2^32=4E9 약 4GB 공간 만큼만 인식이 되고,
64Bit 운영체제의 경우 2^64=1E19 약 16EB 엑사바이트 만큼 인식이 가능하다.
-32Bit용 응용프로그램의 경우 64Bit 운영체제에서는 동작이 가능,
반대의 경우는 불가능(하위 호환만 가능하다.)*/

